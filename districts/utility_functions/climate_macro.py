#generated IDA climate macro (change climate-macro-build): columns of the climate file, the macro written from the
#climate file, the version's site and the modelling settings; no Qt, no DB
import os
import re
import shutil
from dataclasses import dataclass, field

#marker in the macro's header: a macro without it was made by hand and is kept once as .bak
MARKER = 'Generated by Districts Modeler'
HEADER = ';IDA 5.21801 Data UTF-8\n'
FORM_HEADER = ';IDA 5.21801 Form UTF-8\n'
#columns of an IDA climate file without a header row
IDA_LAYOUT = ('time', 'tair', 'relhum', 'winddir', 'windvel', 'idirnorm', 'idiffhor')
#header names of the known quantities (lower case) and their variable in the macro's source file
KNOWN = {'time': 'TIME', 'tair': 'TAIR', 'relhum': 'RELHUM', 'winddir': 'WINDDIR', 'windvel': 'WINDVEL',
         'windx': 'WINDX', 'windy': 'WINDY', 'idirnorm': 'IDIRNORM', 'idiffhor': 'IDIFFHOR', 'skycover': 'SKYCOVER',
         'precipitation': 'PRECIPITATION', 'albedo': 'ALBEDO'}
REQUIRED = ('time', 'tair', 'relhum', 'idirnorm', 'idiffhor')
#objects of the macro: an extra column's gain must not take one of these names (IDA compares names without case)
RESERVED = {'climate_file', 'climate_processor', 'vel', 'vel2', 'v_dx2', 'v_dy2', 'tduct', 'tduct-const', 'tground',
            'tground-const', 'kusuda', 'schedule1', 'sunangle', 'minsunangle', 'max', 'idirtonorm', 'cos', 'idif',
            'idir', 'isolar', 'convertdegreerad', 'sinelev', 'idirhor', 'iglob', 'albedo'}


@dataclass
class ClimateColumns:
    path: str
    header: bool
    #(column number from 1, quantity key or None, name in the file)
    columns: list = field(default_factory=list)

    def number(self, key):
        return next((n for n, k, _ in self.columns if k == key), None)

    @property
    def wind(self):
        """'dirvel' (direction and speed) or 'xy' (WindX/WindY)"""
        return 'xy' if self.number('windx') and self.number('windy') else 'dirvel'

    @property
    def extra(self):
        """(column number, name) of the columns that are not one of the seven basic quantities"""
        basic = set(REQUIRED) | {'winddir', 'windvel', 'windx', 'windy'}
        return [(n, name) for n, k, name in self.columns if k not in basic]


def climateColumns(path):
    """Columns of a climate file: by name from a header row (first line starting with # or holding non-numeric
    tokens), otherwise the IDA layout. ValueError naming the missing quantities and the file's columns."""
    with open(path, encoding='utf-8', errors='replace') as f:
        first = f.readline()
    tokens = first.strip().lstrip('#').split()
    header = first.lstrip().startswith('#') or any(not _isNumber(t) for t in tokens)
    if header:
        columns = [(i + 1, t.lower() if t.lower() in KNOWN else None, t) for i, t in enumerate(tokens)]
    else:
        columns = [(i + 1, IDA_LAYOUT[i] if i < len(IDA_LAYOUT) else None, IDA_LAYOUT[i] if i < len(IDA_LAYOUT)
                    else 'column{}'.format(i + 1)) for i in range(len(tokens))]
    result = ClimateColumns(path, header, columns)
    missing = [k for k in REQUIRED if result.number(k) is None]
    if not (result.number('winddir') and result.number('windvel')) and not (result.number('windx') and result.number('windy')):
        missing.append('winddir/windvel or windx/windy')
    if missing:
        raise ValueError('climate file {}: missing {}; its columns are {}'.format(
            path, ', '.join(missing), ', '.join(name for _, _, name in columns)))
    return result


def _isNumber(text):
    try:
        float(text)
        return True
    except ValueError:
        return False


def _gainName(name, used):
    """an object name for an extra column's gain, unique without case and not one of the macro's objects"""
    base = re.sub(r'[^A-Za-z0-9_]', '_', name) or 'column'
    candidate = base
    while candidate.lower() in used:
        candidate = base + '_col'
    used.add(candidate.lower())
    return candidate


def _lisp(text):
    return '"' + str(text).replace('\\', '\\\\').replace('"', '\\"') + '"'


def _num(value):
    return '{:.10g}'.format(float(value))


def _sparse(default, items):
    return '#S(MS-SPARSE DEFAULT-VALUE {} DIMENSION 1 VALUE ({}))'.format(default, ' '.join(items))


IV = ':IV ' + _sparse('0.0', [])


def _adder(name, inputs, extra=''):
    """ADDER with its inputs bound: inputs as sparse binding items, e.g. '(1 -1 (INSIGNALLINK 1) 0)'"""
    return ('((:EO :N "{}" :T ADDER)\n (:PAR :N N_IN :V {})\n (:PAR :N COEFF :DIM ({}))\n'
            ' (:VAR :N INSIGNAL :DIM ({}) {} :B {}{}))').format(name, len(inputs), len(inputs), len(inputs), IV,
                                                               _sparse('NIL', inputs), extra)


def macroObjects(columns, climate, settings):
    """The macro's objects (.idm text without the document header) and connections, and the signals it provides.
    climate: file_name, latitude, longitude, timezone [h], height; settings: modelling settings (ground_model,
    kusuda_*, ground_temp, duct_temp)."""
    objs, conns = [], []
    signals = ['TAIR2', 'TSKY', 'ELEVSUN', 'vel', 'ISolar', 'IGlob', 'TGround', 'TDuct']
    src = ['((SOURCE-FILE :DOCUMENT-PATH {p} :SF {p} :N "climate_file" :T SOURCE-FILE :COL T)'.format(
        p=_lisp(climate['file_name']))]
    used = set(RESERVED)
    variables = {}
    for n, key, name in columns.columns:
        if key == 'time':
            continue
        var = KNOWN[key] if key else _gainName(name, used).upper()
        variables[(key, name)] = var
        src.append(' (:VAR :N {} :T GENERIC :U || :S (:DEFAULT T 2) :AS {})'.format(var, n))
    objs.append('\n'.join(src) + ')')
    file_var = lambda key: '(:MACRO "climate_file" {})'.format(KNOWN[key])
    # climate processor: site, the file's weather, wind in either form, sky cover and precipitation when given
    proc = ['((:CEO :N "climate_processor" :T ENVIRONMENT)',
            ' (:PAR :N LAT :V {})'.format(_num(climate['latitude'])),
            ' (:PAR :N LONG :V {})'.format(_num(climate['longitude'])),
            ' (:PAR :N LONGTIMEZONE :V {})'.format(_num(float(climate['timezone']) * 15)),
            ' (:PAR :N HEIGHT :V {})'.format(_num(climate['height'])),
            ' (:VAR :N TAIR :B {} :L "climate" :AS "Tair")'.format(file_var('tair')),
            ' (:VAR :N XAIR :B 608)',
            ' (:VAR :N RELHUM :B {})'.format(file_var('relhum'))]
    if columns.wind == 'xy':
        proc += [' (:VAR :N WINDDIR :B 0.0)', ' (:VAR :N WINDVELREF :B 0.0)',
                 ' (:VAR :N WINDX :B {})'.format(file_var('windx')), ' (:VAR :N WINDY :B {})'.format(file_var('windy'))]
    else:
        proc += [' (:VAR :N WINDDIR :B {})'.format(file_var('winddir')),
                 ' (:VAR :N WINDVELREF :B {})'.format(file_var('windvel')), ' (:VAR :N WINDX)', ' (:VAR :N WINDY)']
    proc += [' (:VAR :N IDIRNORM :B {} :L "climate" :AS "directNormalRad")'.format(file_var('idirnorm')),
             ' (:VAR :N IDIFFHOR :B {} :L "climate" :AS "diffuseHorRad")'.format(file_var('idiffhor')),
             ' (:VAR :N SKYCOVER :B {})'.format(file_var('skycover') if columns.number('skycover') else ':IV')]
    if columns.number('precipitation'):
        proc.append(' (:VAR :N PRECIPITATION :B {})'.format(file_var('precipitation')))
    objs.append('\n'.join(proc) + ')')
    # wind velocity
    if columns.wind == 'xy':
        for name, var in (('v_dx2', 'WINDX'), ('v_dy2', 'WINDY')):
            objs.append('((:EO :N "{}" :T MULTIPLIER)\n (:VAR :N INSIGNAL {} :B {}))'.format(name, IV, _sparse(
                'NIL', ['(1 :MACRO "climate_file" {})'.format(var), '(2 :MACRO "climate_file" {})'.format(var)])))
        objs.append(_adder('vel2', ['(1 -1 (INSIGNALLINK 1) 0)', '(2 -1 (INSIGNALLINK 2) 0)']))
        objs.append('((MODEL :N "vel" :T |Sqrt|)\n (:VAR :N |u_var| :B (-1 |u| 0))\n'
                    ' (:VAR :N |y_var| :L "climate" :AS "velocity"))')
        conns += [' (("vel2" (INSIGNALLINK 1)) ("v_dx2" OUTSIGNALLINK) 0 0 NIL)',
                  ' (("vel2" (INSIGNALLINK 2)) ("v_dy2" OUTSIGNALLINK) 0 0 NIL)',
                  ' (("vel" |u|) ("vel2" OUTSIGNALLINK) 0 0 NIL)']
    else:
        objs.append('((MODEL :N "vel" :T |Gain|)\n (:VAR :N |u_var| :B {})\n'
                    ' (:VAR :N |y_var| :L "climate" :AS "velocity"))'.format(file_var('windvel')))
    # vertical irradiation ISolar with the shading schedule, as the climate macro had it
    objs += ['((SCHEDULE :N "Schedule1" :T SCHEDULE)\n (:RES :N SCHEDULE-DATA :V "Shading"))',
             '((SOURCE-CONSTANT :N "convertDegreeRad" :T CONSTANT)\n (:PAR :N X :V 0.017453293))',
             '((:EO :N "sunAngle" :T MULTIPLIER)\n (:VAR :N INSIGNAL {} :B {}))'.format(IV, _sparse(
                 'NIL', ['(1 :MACRO "climate_processor" ELEVSUN)', '(2 -1 (INSIGNALLINK 2) 0)'])),
             '((MODEL :N "Cos" :T |Cos|)\n (:VAR :N |u_var| :B (-1 |u| 0)))',
             '(SOURCE-CONSTANT :N "minSunAngle" :T CONSTANT)',
             '((MODEL :N "Max" :T |Max|)\n (:PAR :N |nin| :V 2)\n (:VAR :N |u_var| :DIM (2) {} :B {}))'.format(
                 IV, _sparse('NIL', ['(1 -1 (|u| 1) 0)', '(2 -1 (|u| 2) 0)'])),
             '((:EO :N "IdirToNorm" :T MULTIPLIER)\n (:PAR :N N_IN :V 3)\n (:VAR :N INSIGNAL :DIM (3) {} :B {}))'.format(
                 IV, _sparse('NIL', ['(1 -1 (INSIGNALLINK 1) 0)', '(2 -1 (INSIGNALLINK 2) 0)',
                                     '(3 -1 (INSIGNALLINK 3) 0)'])),
             _adder('Idif', ['(1 :MACRO "climate_file" IDIFFHOR)']),
             _adder('Idir', ['(1 :MACRO "climate_file" IDIRNORM)'],
                    ' :L {} :AS {}'.format(_sparse('OFF', ['(1 . "climate")']), _sparse('NIL', ['(1 . "IDir")']))),
             ('((:EO :N "ISolar" :T ADDER)\n (:VAR :N OUTSIGNAL :L "climate" :AS "ITot")\n'
              ' (:VAR :N INSIGNAL {} :B {} :L {} :AS {}))').format(
                 IV, _sparse('NIL', ['(1 -1 (INSIGNALLINK 1) 0)', '(2 -1 (INSIGNALLINK 2) 0)']),
                 _sparse('OFF', ['(1 . "climate")', '(2 . "climate")']),
                 _sparse('NIL', ['(1 . "IDiff")', '(2 . "IDir_vert")']))]
    conns += [' (("ISolar" (INSIGNALLINK 2)) ("IdirToNorm" OUTSIGNALLINK) 0 0 NIL)',
              ' (("ISolar" (INSIGNALLINK 1)) ("Idif" OUTSIGNALLINK) 0 0 NIL)',
              ' (("Cos" |u|) ("sunAngle" OUTSIGNALLINK) 0 0 NIL)',
              ' (("IdirToNorm" (INSIGNALLINK 3)) ("Schedule1" OUTSIGNALLINK) 0 0 NIL)',
              ' (("IdirToNorm" (INSIGNALLINK 2)) ("Max" |y|) 0 0 NIL)',
              ' (("IdirToNorm" (INSIGNALLINK 1)) ("Idir" OUTSIGNALLINK) 0 0 NIL)',
              ' (("Max" (|u| 2)) ("minSunAngle" LINK) 0 0 NIL)',
              ' (("Max" (|u| 1)) ("Cos" |y|) 0 0 NIL)',
              ' (("sunAngle" (INSIGNALLINK 2)) ("convertDegreeRad" LINK) 0 0 NIL)']
    # global horizontal radiation IGlob = IDIRNORM * sin(ELEVSUN) + IDIFFHOR (ground collectors)
    objs += ['((MODEL :N "SinElev" :T |Sin|)\n (:VAR :N |u_var| :B (-1 |u| 0)))',
             '((:EO :N "IdirHor" :T MULTIPLIER)\n (:VAR :N INSIGNAL {} :B {}))'.format(IV, _sparse(
                 'NIL', ['(1 :MACRO "climate_file" IDIRNORM)', '(2 -1 (INSIGNALLINK 2) 0)'])),
             _adder('IGlob', ['(1 -1 (INSIGNALLINK 1) 0)', '(2 :MACRO "climate_file" IDIFFHOR)']).replace(
                 '(:EO :N "IGlob" :T ADDER)', '(:EO :N "IGlob" :T ADDER)\n (:VAR :N OUTSIGNAL :L "climate" :AS "IGlob")')]
    conns += [' (("SinElev" |u|) ("sunAngle" OUTSIGNALLINK) 0 0 NIL)',
              ' (("IdirHor" (INSIGNALLINK 2)) ("SinElev" |y|) 0 0 NIL)',
              ' (("IGlob" (INSIGNALLINK 1)) ("IdirHor" OUTSIGNALLINK) 0 0 NIL)']
    # ground and duct temperature from the modelling settings
    if str(settings.get('ground_model', 'Kusuda')).lower() == 'constant':
        objs.append('((SOURCE-CONSTANT :N "TGround-Const" :T CONSTANT)\n (:PAR :N X :V {}))'.format(
            _num(settings.get('ground_temp', 10))))
        conns.append(' (("TGround" (INSIGNALLINK 1)) ("TGround-Const" LINK) 0 0 NIL)')
    else:
        kusuda = [('TSurfMean', 'kusuda_tsurfmean'), ('TSurfAmpl', 'kusuda_tsurfampl'), ('Theta', 'kusuda_theta'),
                  ('Rho', 'kusuda_rho'), ('cp', 'kusuda_cp'), ('lambda', 'kusuda_lambda'), ('Depth', 'kusuda_depth')]
        objs.append('((MODEL :N "Kusuda" :T |kusuda|)\n' + '\n'.join(
            ' (:PAR :N |{}| :V {})'.format(p, _num(settings[k])) for p, k in kusuda) + ')')
        conns.append(' (("TGround" (INSIGNALLINK 1)) ("Kusuda" TEMPLINK) 0 0 NIL)')
    objs.append(_adder('TGround', ['(1 -1 (INSIGNALLINK 1) 0)']))
    objs.append('((SOURCE-CONSTANT :N "TDuct-Const" :T CONSTANT)\n (:PAR :N X :V {}))'.format(
        _num(settings.get('duct_temp', 20))))
    objs.append(_adder('TDuct', ['(1 -1 (INSIGNALLINK 1) 0)']))
    conns.append(' (("TDuct" (INSIGNALLINK 1)) ("TDuct-Const" LINK) 0 0 NIL)')
    # extra columns: a gain each; the albedo as a fraction (the file has %)
    for n, name in columns.extra:
        key = next(k for m, k, _ in columns.columns if m == n)
        var = variables[(key, name)]
        if key == 'albedo':
            objs.append('((MODEL :N "albedo" :T |Gain|)\n (:PAR :N |k| :V 0.01)\n (:VAR :N |u_var| :B {}))'.format(
                '(:MACRO "climate_file" {})'.format(var)))
            signals.append('albedo')
        else:
            gain = var if key is None else _gainName(name, used)
            objs.append('((MODEL :N "{}" :T |Gain|)\n (:VAR :N |u_var| :B (:MACRO "climate_file" {})))'.format(gain, var))
            signals.append(gain)
    return objs, conns, signals


def macroLayout(objs):
    """.idc of the macro: every object in a grid (the schema is only for looking at it in IDA)"""
    icons = {'SOURCE-FILE': ('sys:source-file.ids', 'SOURCE-FILE', 56.5, 20), ':CEO': ('lib:climate.ids', ':CEO', 15, 15),
             'SOURCE-CONSTANT': ('sys:constant.ids', 'SOURCE-CONSTANT', 23.9, 10), ':EO': ('lib:adder.ids', ':EO', 16, 16),
             'SCHEDULE': ('lib:schedule.ids', 'SCHEDULE', 24, 16), 'MODEL': ('sys:eo.ids', 'MODEL', 16, 16)}
    lines = [FORM_HEADER + '(DOCUMENT-HEADER :TYPE SCHEMA :PAGE-WIDTH 178 :PAGE-HEIGHT 120) ']
    for k, obj in enumerate(objs):
        m = re.match(r'\(+(SOURCE-FILE|:CEO|SOURCE-CONSTANT|:EO|SCHEDULE|MODEL).*?:N "([^"]+)"', obj)
        if not m:
            continue
        icon, data, rx, ry = icons[m.group(1)]
        lines.append('(EQUATION-FRAME :AT (({} {})) :R ({} {}) :ICON "{}" :SLOT ("{}") :NAME "{}" :DATA {}) '.format(
            60 + 90 * (k % 7), 40 + 60 * (k // 7), rx, ry, icon, m.group(2), m.group(2), data))
    lines.append('(SELF-FRAME :AT ((352 190)) :R (342 176) :SLOT (:SELF) :DATA MACRO-OBJECT) ')
    return '\n'.join(lines) + '\n'


def writeClimateMacro(folder, climate, settings):
    """Writes climate-macro.idm and .idc into folder from the climate file (climate['file_name']), the site and the
    modelling settings; a macro there that the generator did not write is kept once as climate-macro.idm.bak.
    Returns the signals the macro provides."""
    columns = climateColumns(climate['file_name'])
    objs, conns, signals = macroObjects(columns, climate, settings)
    os.makedirs(folder, exist_ok=True)
    idm_path = os.path.join(folder, 'climate-macro.idm')
    keepHandMade(idm_path)
    text = (HEADER + '(DOCUMENT-HEADER :TYPE DISTRICTS-MACRO :D "{}" :APP (DISTRICTS :VER 1.0)) \n'.format(MARKER)
            + '\n'.join(objs) + '\n(CONNECTIONS\n' + '\n'.join(conns) + ')\n')
    with open(idm_path, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(text)
    with open(os.path.join(folder, 'climate-macro.idc'), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(macroLayout(objs))
    return signals


def keepHandMade(idm_path):
    """a macro without the generator's marker is copied once to climate-macro.idm.bak (an existing .bak stays)"""
    if not os.path.exists(idm_path) or os.path.exists(idm_path + '.bak'):
        return
    with open(idm_path, encoding='utf-8', errors='replace') as f:
        if MARKER in f.read(400):
            return
    shutil.copy2(idm_path, idm_path + '.bak')
